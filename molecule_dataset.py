class TransformationMoleculeDataset(Dataset):
    """
    Dataset for supervised pretraining on molecule transformation sequences (A -> B).

    Loads data where each key is a starting molecule SMILES (A) and the value is a list
    of successful transformation sequences originating from A. Each sequence is a tuple:
    (start_smiles_A, end_smiles_B, action_sequence: List[int]).

    Each datapoint generated by __getitem__ represents an intermediate state during
    a transformation. It samples a transformation sequence and a step within it,
    reconstructs the molecule state up to that step by applying actions to the
    starting molecule A, and provides the action at that step as the target label.

    __getitem__ returns a dictionary for a SINGLE sample:
    {'molecule': MoleculeDesign, 'target_action': int}
    Batching is handled by the DataLoader using a collate_fn (e.g., MoleculeDesign.list_to_batch).
    """
    def __init__(self, config: MoleculeConfig, path_to_pickle: str, no_random: bool = False):
        """
        Args:
            config: MoleculeConfig instance.
            path_to_pickle: Path to the preprocessed transformations dictionary pickle file.
            no_random: If True, pre-shuffles the sample list for deterministic epoch ordering
                       (DataLoader's shuffle=True is the more standard way).
        """
        self.config = config
        self.path_to_pickle = path_to_pickle
        self.no_random = no_random

        print(f"Loading transformation dataset from: {path_to_pickle}")
        if not os.path.exists(path_to_pickle):
             raise FileNotFoundError(f"Dataset pickle file not found at: {path_to_pickle}")

        try:
            with open(path_to_pickle, "rb") as f:
                # Expecting Dict[str, List[Tuple[str, str, List[int]]]]
                self.transformations_dict: Dict[str, List[Tuple[str, str, List[int]]]] = pickle.load(f)
            if not isinstance(self.transformations_dict, dict):
                raise TypeError(f"Loaded data from {path_to_pickle} is not a dictionary (type: {type(self.transformations_dict)}).")
            print(f"Loaded data for {len(self.transformations_dict)} starting molecules.")
        except Exception as e:
            print(f"Error loading dataset pickle '{path_to_pickle}': {e}")
            raise

        # --- Create list of targets to sample ---
        # Each element: (start_smiles_key: str, transformation_list_idx: int, action_step_idx: int)
        self.targets_to_sample: List[Tuple[str, int, int]] = []
        skipped_entries = 0
        total_transformations = 0

        print("Preprocessing dataset to identify sample points...")
        for start_smiles_key, transformations_list in self.transformations_dict.items():
            if not isinstance(transformations_list, list):
                 # print(f"Warning: Value for key '{start_smiles_key}' is not a list, skipping.") # Can be verbose
                 skipped_entries += 1
                 continue

            total_transformations += len(transformations_list)
            for trans_idx, transformation_data in enumerate(transformations_list):
                is_valid_format = (
                    isinstance(transformation_data, tuple) and
                    len(transformation_data) == 3 and
                    isinstance(transformation_data[0], str) and # start_smiles
                    isinstance(transformation_data[1], str) and # end_smiles
                    isinstance(transformation_data[2], list)   # action_sequence
                )
                if not is_valid_format:
                     # print(f"Warning: Invalid transformation data format for '{start_smiles_key}', list index {trans_idx}. Skipping.") # Can be verbose
                     skipped_entries += 1
                     continue

                action_sequence = transformation_data[2]
                if not action_sequence: continue # Skip empty sequences

                # Add a sample point for each action step in the sequence
                self.targets_to_sample.extend([(start_smiles_key, trans_idx, step_idx) for step_idx in range(len(action_sequence))])

        if skipped_entries > 0:
             print(f"Warning: Skipped {skipped_entries} invalid entries during dataset preprocessing.")

        if not self.targets_to_sample:
             raise ValueError("No valid action steps found to sample from the dataset. Check data format and content.")

        # --- Set Dataset Length ---
        self.length = len(self.targets_to_sample) # Length is the total number of individual samples

        print(f"Dataset contains {len(self.transformations_dict)} starting molecules, "
              f"{total_transformations} total transformation sequences, and "
              f"{self.length} total action steps (datapoints).")

        if self.no_random:
             print("Note: Pre-shuffling sample list for deterministic epochs (no_random=True).")
             random.shuffle(self.targets_to_sample)


    def __len__(self):
        """Returns the total number of individual action steps (samples) in the dataset."""
        return self.length

    def __getitem__(self, idx: int) -> Dict:
        """
        Generates one training sample.

        Args:
            idx: The index of the sample in the flattened list of all possible
                 (sequence, step) combinations.

        Returns:
            A dictionary containing:
                'molecule': The MoleculeDesign object reconstructed up to the
                            step *before* the target action.
                'target_action': The integer index of the action to be predicted
                                 at this step.

        Raises:
            IndexError: If idx is out of bounds.
            RuntimeError: If molecule reconstruction fails (e.g., invalid start SMILES,
                          error during take_action).
        """
        if not 0 <= idx < self.length:
             raise IndexError(f"Index {idx} out of bounds for dataset with length {self.length}")

        try:
            # --- 1. Select the target sample ---
            # idx directly maps to the pre-processed list of all possible steps
            target_info = self.targets_to_sample[idx]
            start_smiles_key, trans_idx, action_step_idx = target_info

            # --- 2. Retrieve sequence and target action ---
            transformation_data = self.transformations_dict[start_smiles_key][trans_idx]
            full_action_seq = transformation_data[2]
            target_action = full_action_seq[action_step_idx] # The action to predict

            # --- 3. Initialize MoleculeDesign from starting SMILES ---
            result_tuple = MoleculeDesign.from_smiles(self.config, start_smiles_key)
            if result_tuple is None:
                 raise RuntimeError(f"Failed to initialize MoleculeDesign from starting SMILES '{start_smiles_key}' for sample index {idx}.")
            molecule, _ = result_tuple

            # --- 4. Apply actions up to the target step ---
            actions_to_apply = full_action_seq[:action_step_idx]
            for i, action in enumerate(actions_to_apply):
                try:
                    molecule.take_action(action)
                except Exception as e_take_action:
                     # Raise error if reconstruction fails mid-way
                     raise RuntimeError(f"Error during take_action({action}) at step {i} reconstructing state for '{start_smiles_key}' (trans {trans_idx}, step {action_step_idx}, sample_idx {idx}): {e_take_action}")

            # --- 5. Return the reconstructed molecule and the target action ---
            return {
                'molecule': molecule,
                'target_action': target_action
            }

        except KeyError as e_key:
            # Catch potential issues if keys are missing during data retrieval
            raise RuntimeError(f"Data access error for sample index {idx}: Missing key {e_key}") from e_key
        except IndexError as e_idx:
             # Catch potential issues if list indices are wrong during data retrieval
             raise RuntimeError(f"Data access error for sample index {idx}: Index out of bounds {e_idx}") from e_idx
        except Exception as e_outer:
            # Catch any other unexpected errors during processing for this index
            raise RuntimeError(f"Unexpected error processing sample index {idx}: {e_outer}") from e_outer


